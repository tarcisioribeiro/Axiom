"""
Tests for requirement 8 of the debt payment plan epic: an Expense can only
be linked, by manual user choice, to one of related_loan/related_payable —
never both at once (a single expense can't pay off a loan installment and a
payable installment simultaneously).

Decision 5.1 (revised): fixed_expense_template is NOT part of this
exclusivity — it's just a reference to the FixedExpense that generated the
expense, with no effect on payment, and legitimately coexists with
related_loan/related_payable both in expenses auto-generated by
bulk_generate_fixed_expenses and in later manual edits (e.g. confirming
payment of an installment that is itself linked to a Payable).
"""

from datetime import date, time
from decimal import Decimal

from django.contrib.auth.models import User
from django.test import TestCase

from accounts.models import Account
from expenses.models import Expense, FixedExpense
from expenses.serializers import ExpenseSerializer
from expenses.services import bulk_generate_fixed_expenses
from loans.models import Loan
from members.models import Member
from payables.models import Payable


def _make_account(name="ExclAcc"):
    return Account.objects.create(
        account_name=name,
        institution_name="NUB",
        account_type="CC",
        is_active=True,
    )


def _make_payable(value="300.00"):
    return Payable.objects.create(
        description="Conta a pagar",
        value=Decimal(value),
        date=date.today(),
        category="others",
        status="active",
    )


class ExpenseLinkExclusivitySerializerTest(TestCase):
    def setUp(self):
        self.user = User.objects.create_user(
            username="excltest",
            email="excl@test.com",
            password="testpass123",
            is_superuser=True,
        )
        self.account = _make_account()
        self.payable = _make_payable()
        self.fixed_expense = FixedExpense.objects.create(
            description="Assinatura",
            default_value=Decimal("50.00"),
            category="digital signs",
            account=self.account,
            due_day=10,
            is_active=True,
        )
        self.member = Member.objects.create(
            name="M", document_hash="x" * 64, phone="11999999999", sex="M"
        )
        self.loan = Loan.objects.create(
            description="Emp",
            value=Decimal("500.00"),
            payed_value=Decimal("0.00"),
            date=date.today(),
            horary=time(10, 0),
            category="loans",
            account=self.account,
            benefited=self.member,
            creditor=self.member,
            installments=1,
            loan_type="lent",
            created_by=self.user,
        )

    def _base_payload(self, **overrides):
        payload = {
            "description": "Despesa manual",
            "value": "100.00",
            "date": str(date.today()),
            "horary": "10:00:00",
            "category": "others",
            "account": self.account.id,
            "payed": False,
        }
        payload.update(overrides)
        return payload

    def test_expense_rejects_two_simultaneous_links(self):
        payload = self._base_payload(
            related_payable=self.payable.id,
            related_loan=self.loan.id,
        )
        serializer = ExpenseSerializer(data=payload)
        self.assertFalse(serializer.is_valid())
        self.assertIn("related_loan", serializer.errors)

    def test_expense_allows_single_link(self):
        payload = self._base_payload(related_payable=self.payable.id)
        serializer = ExpenseSerializer(data=payload)
        self.assertTrue(serializer.is_valid(), serializer.errors)

    def test_expense_allows_no_link(self):
        payload = self._base_payload()
        serializer = ExpenseSerializer(data=payload)
        self.assertTrue(serializer.is_valid(), serializer.errors)

    def test_expense_allows_fixed_expense_template_with_related_payable(self):
        """fixed_expense_template has no payment effect, so it's exempt from
        the related_loan/related_payable exclusivity on manual creation."""
        payload = self._base_payload(
            related_payable=self.payable.id,
            fixed_expense_template=self.fixed_expense.id,
        )
        serializer = ExpenseSerializer(data=payload)
        self.assertTrue(serializer.is_valid(), serializer.errors)

    def test_update_rejects_adding_second_link_to_existing_single_link(self):
        expense = Expense.objects.create(
            description="Já vinculada",
            value=Decimal("100.00"),
            date=date.today(),
            horary=time(10, 0),
            category="others",
            account=self.account,
            payed=False,
            related_payable=self.payable,
        )
        serializer = ExpenseSerializer(
            expense,
            data={"related_loan": self.loan.id},
            partial=True,
        )
        self.assertFalse(serializer.is_valid())
        self.assertIn("related_loan", serializer.errors)

    def test_update_adds_fixed_template_to_existing_payable_link(self):
        """Manually linking a FixedExpense template to an expense that
        already pays off a Payable must not be rejected — this is exactly
        the case the user needs: keep related_payable so paying the expense
        updates the payable's paid value, while also tagging which
        recurring template generated it."""
        expense = Expense.objects.create(
            description="Já vinculada",
            value=Decimal("100.00"),
            date=date.today(),
            horary=time(10, 0),
            category="others",
            account=self.account,
            payed=False,
            related_payable=self.payable,
        )
        serializer = ExpenseSerializer(
            expense,
            data={"fixed_expense_template": self.fixed_expense.id},
            partial=True,
        )
        self.assertTrue(serializer.is_valid(), serializer.errors)

    def test_update_untouched_pre_existing_double_link_does_not_reject(self):
        """
        Regression test: an Expense auto-generated by
        bulk_generate_fixed_expenses (bypasses this serializer, see
        BulkGenerateExemptFromExclusivityTest below) legitimately carries
        both `fixed_expense_template` and `related_payable` from birth.

        Before this fix, ANY later update through this serializer — e.g.
        confirming payment via `payed=True` — re-evaluated those two
        pre-existing, untouched links and rejected the request forever,
        making the installment impossible to confirm as paid from the UI.
        """
        expense = Expense.objects.create(
            description="Parcela dívida (auto-gerada)",
            value=Decimal("100.00"),
            date=date.today(),
            horary=time(10, 0),
            category="others",
            account=self.account,
            payed=False,
            related_payable=self.payable,
            fixed_expense_template=self.fixed_expense,
        )
        serializer = ExpenseSerializer(
            expense,
            data={"payed": True},
            partial=True,
        )
        self.assertTrue(serializer.is_valid(), serializer.errors)


class BulkGenerateExemptFromExclusivityTest(TestCase):
    """Auto-generated expenses from the debt-installment FixedExpense
    pipeline legitimately carry both fixed_expense_template and
    related_payable — bulk_generate_fixed_expenses bypasses the
    serializer entirely, so decision 5.1's exemption holds without any
    extra flag."""

    def setUp(self):
        self.user = User.objects.create_user(
            username="bulkexcltest",
            email="bulkexcl@test.com",
            password="testpass123",
            is_superuser=True,
        )
        self.account = _make_account()
        self.payable = _make_payable()
        self.fixed_expense = FixedExpense.objects.create(
            description="Parcela dívida",
            default_value=Decimal("100.00"),
            category="others",
            account=self.account,
            due_day=10,
            is_active=True,
            allow_value_edit=False,
            related_payable=self.payable,
        )

    def test_bulk_generate_exempt_from_exclusivity(self):
        today = date.today()
        month = f"{today.year}-{today.month:02d}"
        result = bulk_generate_fixed_expenses(
            month,
            [{"fixed_expense_id": self.fixed_expense.id, "value": 100.00}],
            self.user,
        )
        self.assertEqual(result["created_count"], 1)
        expense = result["expenses"][0]
        self.assertEqual(
            expense.fixed_expense_template_id, self.fixed_expense.id
        )
        self.assertEqual(expense.related_payable_id, self.payable.id)
